using System.Globalization;
using System.IO;
using System.Text;
using System.Windows;
using System.Windows.Media;
using System.Windows.Media.Imaging;

// One source of truth for the logo: shapes on a 512×512 canvas, rendered to SVG, PNG, ICO and Android vectors.
static class Logo
{
    public const string Blue = "#1A5FB4", BlueLight = "#2F7FE0", Green = "#2EB872", White = "#FFFFFF";

    public record Shape(string Path, string? Fill, string? Stroke = null, double StrokeWidth = 0);

    static string F(FormattableString s) => s.ToString(CultureInfo.InvariantCulture);

    static string Circle(double cx, double cy, double r) =>
        F($"M {cx - r} {cy} A {r} {r} 0 1 0 {cx + r} {cy} A {r} {r} 0 1 0 {cx - r} {cy} Z");

    public static readonly Shape[] Foreground =
    [
        // Crop-frame corners.
        new("M 96 180 L 96 96 L 180 96", null, White, 30),
        new("M 332 96 L 416 96 L 416 180", null, White, 30),
        new("M 96 332 L 96 416 L 180 416", null, White, 30),
        // Person: head and shoulders.
        new(Circle(256, 214, 64), White),
        new("M 148 402 C 148 326 198 296 256 296 C 314 296 364 326 364 402 Z", White),
        // "Verified" badge over the bottom-right corner.
        new(Circle(394, 394, 84), Green, Blue, 18),
        new("M 352 396 L 382 426 L 438 368", null, White, 26),
    ];

    static Color C(string hex) => (Color)ColorConverter.ConvertFromString(hex);

    public static Drawing Build(bool withBackground)
    {
        var g = new DrawingGroup();
        if (withBackground)
        {
            var bg = new LinearGradientBrush(C(BlueLight), C(Blue), new Point(0, 0), new Point(1, 1));
            g.Children.Add(new GeometryDrawing(bg, null, new RectangleGeometry(new Rect(0, 0, 512, 512), 112, 112)));
        }

        foreach (var s in Foreground)
        {
            Brush? fill = s.Fill is null ? null : new SolidColorBrush(C(s.Fill));
            Pen? pen = s.Stroke is null ? null : new Pen(new SolidColorBrush(C(s.Stroke)), s.StrokeWidth)
            {
                StartLineCap = PenLineCap.Round,
                EndLineCap = PenLineCap.Round,
                LineJoin = PenLineJoin.Round,
            };
            g.Children.Add(new GeometryDrawing(fill, pen, Geometry.Parse(s.Path)));
        }

        return g;
    }

    public static byte[] Png(int size, bool withBackground = true)
    {
        var visual = new DrawingVisual();
        using (var dc = visual.RenderOpen())
        {
            dc.PushTransform(new ScaleTransform(size / 512.0, size / 512.0));
            dc.DrawDrawing(Build(withBackground));
        }

        var rtb = new RenderTargetBitmap(size, size, 96, 96, PixelFormats.Pbgra32);
        rtb.Render(visual);
        var enc = new PngBitmapEncoder();
        enc.Frames.Add(BitmapFrame.Create(rtb));
        using var ms = new MemoryStream();
        enc.Save(ms);
        return ms.ToArray();
    }

    public static string Svg()
    {
        var sb = new StringBuilder();
        sb.AppendLine("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 512 512\" width=\"512\" height=\"512\">");
        sb.AppendLine("  <title>DV Photo Validator</title>");
        sb.AppendLine($"  <defs><linearGradient id=\"bg\" x1=\"0\" y1=\"0\" x2=\"1\" y2=\"1\"><stop offset=\"0\" stop-color=\"{BlueLight}\"/><stop offset=\"1\" stop-color=\"{Blue}\"/></linearGradient></defs>");
        sb.AppendLine("  <rect width=\"512\" height=\"512\" rx=\"112\" fill=\"url(#bg)\"/>");
        foreach (var s in Foreground)
        {
            var stroke = s.Stroke is null ? "" : F($" stroke=\"{s.Stroke}\" stroke-width=\"{s.StrokeWidth}\" stroke-linecap=\"round\" stroke-linejoin=\"round\"");
            sb.AppendLine($"  <path d=\"{s.Path}\" fill=\"{s.Fill ?? "none"}\"{stroke}/>");
        }

        sb.AppendLine("</svg>");
        return sb.ToString();
    }

    /// <summary>Android adaptive-icon foreground: 108×108 viewport, artwork kept inside the 66-unit safe circle.</summary>
    public static string AndroidForeground()
    {
        const double scale = 0.12;
        var offset = (108 - 512 * scale) / 2;
        var sb = new StringBuilder();
        sb.AppendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
        sb.AppendLine("<!-- Generated by branding/generator (same shapes as branding/logo.svg). -->");
        sb.AppendLine("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"");
        sb.AppendLine("    android:width=\"108dp\"");
        sb.AppendLine("    android:height=\"108dp\"");
        sb.AppendLine("    android:viewportWidth=\"108\"");
        sb.AppendLine("    android:viewportHeight=\"108\">");
        sb.AppendLine(F($"    <group android:scaleX=\"{scale}\" android:scaleY=\"{scale}\" android:translateX=\"{offset:0.###}\" android:translateY=\"{offset:0.###}\">"));
        foreach (var s in Foreground)
        {
            sb.Append($"        <path android:pathData=\"{s.Path}\"");
            if (s.Fill is not null)
            {
                sb.Append($" android:fillColor=\"{s.Fill}\"");
            }

            if (s.Stroke is not null)
            {
                sb.Append(F($" android:strokeColor=\"{s.Stroke}\" android:strokeWidth=\"{s.StrokeWidth}\" android:strokeLineCap=\"round\" android:strokeLineJoin=\"round\""));
            }

            sb.AppendLine(" />");
        }

        sb.AppendLine("    </group>");
        sb.AppendLine("</vector>");
        return sb.ToString();
    }

    /// <summary>ICO with PNG-compressed frames (supported since Windows Vista).</summary>
    public static byte[] Ico(int[] sizes)
    {
        var images = sizes.Select(s => Png(s)).ToArray();
        using var ms = new MemoryStream();
        using var w = new BinaryWriter(ms);
        w.Write((short)0);
        w.Write((short)1);
        w.Write((short)sizes.Length);
        var offset = 6 + 16 * sizes.Length;
        for (var i = 0; i < sizes.Length; i++)
        {
            var dim = (byte)(sizes[i] >= 256 ? 0 : sizes[i]);
            w.Write(dim);
            w.Write(dim);
            w.Write((byte)0);
            w.Write((byte)0);
            w.Write((short)1);
            w.Write((short)32);
            w.Write(images[i].Length);
            w.Write(offset);
            offset += images[i].Length;
        }

        foreach (var img in images)
        {
            w.Write(img);
        }

        w.Flush();
        return ms.ToArray();
    }
}

static class Program
{
    [STAThread]
    static void Main(string[] args)
    {
        var outDir = args[0];
        Directory.CreateDirectory(outDir);
        File.WriteAllText(Path.Combine(outDir, "logo.svg"), Logo.Svg());
        foreach (var s in new[] { 1024, 512, 256, 128, 64, 48, 32, 16 })
        {
            File.WriteAllBytes(Path.Combine(outDir, $"logo-{s}.png"), Logo.Png(s));
        }

        File.WriteAllBytes(Path.Combine(outDir, "app.ico"), Logo.Ico([16, 24, 32, 48, 64, 128, 256]));
        File.WriteAllText(Path.Combine(outDir, "ic_launcher_foreground.xml"), Logo.AndroidForeground());

        // Contact sheet: sizes side by side on light and dark backgrounds, for review.
        var sizes = new[] { 256, 128, 64, 48, 32, 16 };
        var visual = new DrawingVisual();
        using (var dc = visual.RenderOpen())
        {
            dc.DrawRectangle(Brushes.White, null, new Rect(0, 0, 640, 300));
            dc.DrawRectangle(new SolidColorBrush(Color.FromRgb(32, 33, 36)), null, new Rect(0, 300, 640, 300));
            foreach (var top in new[] { 0, 300 })
            {
                double x = 20;
                foreach (var s in sizes)
                {
                    var bmp = new BitmapImage();
                    bmp.BeginInit();
                    bmp.StreamSource = new MemoryStream(Logo.Png(s));
                    bmp.EndInit();
                    dc.DrawImage(bmp, new Rect(x, top + 22 + (256 - s) / 2.0, s, s));
                    x += s + 20;
                }
            }
        }

        var sheet = new RenderTargetBitmap(640, 600, 96, 96, PixelFormats.Pbgra32);
        sheet.Render(visual);
        var enc = new PngBitmapEncoder();
        enc.Frames.Add(BitmapFrame.Create(sheet));
        using var f = File.Create(Path.Combine(outDir, "preview.png"));
        enc.Save(f);
    }
}
